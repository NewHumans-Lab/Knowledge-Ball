import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const sql = await readFile('supabase/migrations/202608220001_lineage_server_projection_revalidation_v1.sql', 'utf8');

// Modules 1-3 must have a server-side projection before revalidation can trust
// history/opposition roles supplied by a browser.
assert.match(sql, /create schema if not exists private/);
assert.match(sql, /create table private\.knowledge_lineage_members/);
assert.match(sql, /knowledge_lineage_one_current_per_topic/);
assert.match(sql, /knowledge_lineage_one_pending_head_change/);
assert.match(sql, /alter table private\.knowledge_lineage_members enable row level security/);
assert.match(sql, /revoke all on private\.knowledge_lineage_members from public, anon, authenticated/);
assert.match(sql, /create trigger project_knowledge_lineage_event/);
assert.match(sql, /KnowledgeAdded[\s\S]*candidate-history[\s\S]*candidate-opposition/);
assert.match(sql, /KnowledgeVerdictFinalized[\s\S]*lineage_promote_optimization[\s\S]*lineage_promote_opposition/);
assert.match(sql, /protocol lifecycle events are server-only/);
assert.match(sql, /lineage candidate target is not the stable current head/);

// First-round V2 stays a separate protocol. Module 4 must not rewrite it.
assert.doesNotMatch(sql, /alter table public\.knowledge_pending_vote_rounds/i);
assert.doesNotMatch(sql, /create or replace function public\.finalize_pending_vote_round/i);
assert.doesNotMatch(sql, /create or replace function public\.cast_pending_knowledge_vote/i);

// Later verification is its own frozen V1 state machine.
assert.match(sql, /create table private\.knowledge_revalidation_rounds/);
assert.match(sql, /policy_version='ORIGINAL_DESIGN_V1'/);
assert.match(sql, /deadline=opened_at\+interval '720 hours'/);
assert.match(sql, /create table private\.knowledge_revalidation_votes/);
assert.match(sql, /unique\(round_id,voter_id\)/);
assert.match(sql, /knowledge_revalidation_one_open_topic/);
assert.match(sql, /pg_advisory_xact_lock\(hashtextextended\('knowledge-revalidation:'\|\|member\.topic_id,0\)\)/);

// Frozen challengePolicy: 0=10 GLOBAL, 1=10 LOCAL_10, then exactly the
// 50..100 gate list in global/local pairs. Higher tiers are generated by the
// same decimal 1..9 ladder rather than capped.
assert.match(sql, /challenge_stage=0[\s\S]*10\.000000::numeric,'GLOBAL'/);
assert.match(sql, /challenge_stage=1[\s\S]*10\.000000::numeric,'LOCAL_10'/);
assert.match(sql, /array\[50,60,70,80,90,91,92,93,94,95,96,97,98,99,100\]/);
assert.match(sql, /tier_index:=gated_index\/cycle_length/);
assert.match(sql, /mod\(tier_index,9\)\+1/);
assert.match(sql, /power\(10::numeric,\(tier_index\/9\)\+1\)/);
assert.match(sql, /local_hop_limit:=case when scope='LOCAL_10' then 10 else null end/);

// The whole round uses the round stake. There is no draft-era fixed one-energy
// ordinary vote in second/subsequent verification.
assert.match(sql, /balance=balance-r\.stake/);
assert.match(sql, /CHALLENGE_VOTE_STAKE/);
assert.match(sql, /values\(r\.id,actor,vote_side,r\.stake,tx\)/);
assert.doesNotMatch(sql, /CHALLENGE_VOTE_STAKE[\s\S]{0,500}1\.000000/);
assert.match(sql, /challenge initiator cannot cast an ordinary vote in the same round/);

// V1 timeout includes the initiator AGREE position only at timeout; threshold
// counts are ordinary ballots only.
assert.match(sql, /if agree_count>=r\.required_votes/);
assert.match(sql, /elsif disagree_count>=r\.required_votes/);
assert.match(sql, /if agree_count\+1=disagree_count/);
assert.match(sql, /agree_count\+1>disagree_count/);

// Ledger writes are append-only, exact to 1e-6, idempotent and conserved.
assert.match(sql, /CHALLENGE_STAKE/);
assert.match(sql, /CHALLENGE_SETTLEMENT/);
assert.match(sql, /stake_atoms:=\(r\.stake\*1000000\)::bigint/);
assert.match(sql, /challenge-settlement:/);
assert.match(sql, /perform public\.assert_energy_conservation\(\)/g);
assert.match(sql, /idempotency key reused with different challenge request/);
assert.match(sql, /idempotency key reused with different revalidation vote/);

// Revalidation changes only disputed/current lineage through server lifecycle
// events; client event batches cannot forge those transitions.
assert.match(sql, /KnowledgeRevalidationStarted/);
assert.match(sql, /KnowledgeRevalidationFinalized/);
assert.match(sql, /set revalidating=true/);
assert.match(sql, /lineage_reactivate_history/);
assert.match(sql, /lineage_reactivate_opposition/);
assert.match(sql, /select '202608220001'::text/);

console.log('Knowledge Lineage V3 server projection and ORIGINAL_DESIGN_V1 revalidation migration checks passed');
